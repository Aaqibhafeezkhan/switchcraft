#!/usr/bin/env bash
# shellcheck shell=bash
# terraform.sh — one HCP Terraform / OpenTofu account per profile.
#
# `terraform login` writes $HOME/.terraform.d/credentials.tfrc.json, and that
# directory is relocatable by no environment variable, so a login is strictly
# one account per machine. The CLI config *file* is relocatable, via
# TF_CLI_CONFIG_FILE — so each profile gets its own *.tfrc holding a
# credentials block, and every managed directory's .envrc points there.

# Provenance. Overwrite and teardown both trust only this marker, so a tf_rc
# aimed at a file the user wrote is never eaten. Specific to this file type on
# purpose: the generated git profile also says "Generated by switchcraft", and
# a tf_rc pointed at one of those must not count as ours.
SC_TF_MARK='# Terraform CLI config generated by switchcraft'
SC_TF_DEFAULT_HOST='app.terraform.io'

# Overridable via tf_rc, like claude_dir / gh_dir. Named *.tfrc because that is
# the pattern Terraform documents for a TF_CLI_CONFIG_FILE target.
sc_tf_rc_file() {
	sc_cfg_get "$1" tf_rc "$(sc_xdg_config)/switchcraft/terraform-$1.tfrc"
}

# sc_tf_hosts <profile> — every tf_host, one per line, or the default.
sc_tf_hosts() {
	local out
	out="$(sc_cfg_get_all "$1" tf_host)"
	[[ -n "$out" ]] || out="$SC_TF_DEFAULT_HOST"
	printf '%s\n' "$out"
}

# sc_tf_enabled <profile> — the layer is implied by its data, the way
# github_user implies the gh layer. A profile that says nothing about Terraform
# gets nothing: the export makes Terraform ignore the user's own ~/.terraformrc,
# and that is not ours to switch off uninvited.
sc_tf_enabled() {
	local p="$1" k
	for k in tf_token_cmd tf_host tf_rc tf_rc_extra; do
		[[ -n "$(sc_cfg_get "$p" "$k")" ]] && return 0
	done
	return 1
}

sc_tf_any_enabled() {
	local p
	while IFS= read -r p; do
		[[ -n "$p" ]] || continue
		sc_tf_enabled "$p" && return 0
	done < <(sc_cfg_profiles)
	return 1
}

# sc_tf_host_ok <host> — a host becomes an HCL label, a URL and part of an
# environment variable name. Terraform punycodes non-ASCII hosts, which bash
# cannot do, so they are refused instead of silently encoded wrong.
#
# LC_ALL=C is the load-bearing line: under en_US.UTF-8 the range a-z collates
# accented letters too, so 'café.fr' passed this test and reached the generated
# file. Byte ranges only.
sc_tf_host_ok() {
	# shellcheck disable=SC2034 # LC_ALL is read by the regex engine, not by us
	local LC_ALL=C
	[[ "$1" =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?)*$ ]]
}

# sc_tf_token_ok <token> — the alphabet real HCP Terraform and TFE tokens use.
# Validating beats escaping: the CLI config is HCL1, where what an embedded ${
# means is ambiguous, and a mis-escaped token fails in a way nobody can debug.
# LC_ALL=C for the same collation reason as sc_tf_host_ok.
sc_tf_token_ok() {
	# shellcheck disable=SC2034 # LC_ALL is read by the regex engine, not by us
	local LC_ALL=C
	[[ "$1" =~ ^[A-Za-z0-9._~+/=-]+$ ]]
}

# sc_tf_escape <string> — the two escapes an HCL1 string literal defines.
# Defence in depth; sc_tf_token_ok already refuses anything that needs it.
sc_tf_escape() {
	local s="$1"
	s="${s//\\/\\\\}"
	s="${s//\"/\\\"}"
	printf '%s\n' "$s"
}

# sc_tf_env_name <host> — Terraform's own encoding: dots become _, hyphens __,
# so a host containing both can still be decoded.
sc_tf_env_name() {
	local h="$1"
	# tr, not ${h,,}: bash 3.2 ships on stock macOS. LC_ALL=C so the fold is
	# byte-wise, matching what sc_tf_host_ok allowed through.
	h="$(printf '%s' "$h" | LC_ALL=C tr '[:upper:]' '[:lower:]')"
	h="${h//-/__}"
	h="${h//./_}"
	printf 'TF_TOKEN_%s\n' "$h"
}

# sc_tf_env_tokens — the NAMES of any TF_TOKEN_* in the environment, never the
# values, so doctor cannot print a token by accident.
sc_tf_env_tokens() { compgen -v TF_TOKEN_ || true; }

# sc_tf_token <profile> — resolves tf_token_cmd, never stores the secret.
# Deliberately not token_cmd: that one yields a GitHub PAT, and sending it to
# app.terraform.io would hand your GitHub credentials to a third party.
sc_tf_token() {
	local cmd
	cmd="$(sc_cfg_get "$1" tf_token_cmd)"
	[[ -n "$cmd" ]] || return 0
	# shellcheck disable=SC2086 # tf_token_cmd is a command line by design
	eval $cmd 2>/dev/null | head -n 1
}

# sc_tf_rc_body <profile> — the generated CLI config, to stdout.
# No timestamp anywhere: a re-run has to be byte-identical.
sc_tf_rc_body() {
	local p="$1" host token extra
	cat <<EOF
$SC_TF_MARK — profile: $p
# Edit your config, not this file:
#   switchcraft add --tf-token-cmd / --tf-host   ($(sc_cfg_path))
#
# Each managed directory's .envrc points TF_CLI_CONFIG_FILE here, so your own
# ~/.terraformrc is NOT read while you are inside one: Terraform reads a single
# CLI config file, it does not merge them. To keep yours, add to the profile:
#   tf_rc_extra = ~/.terraformrc
EOF

	# Resolved once, not once per host: every tf_host of a profile shares the
	# token, and one password-manager prompt is enough.
	token="$(sc_tf_token "$p")"

	while IFS= read -r host; do
		[[ -n "$host" ]] || continue
		printf '\n'
		if ! sc_tf_host_ok "$host"; then
			warn "profile '$p': '$host' is not a hostname — skipped"
			printf '# Skipped %s: not a hostname switchcraft can encode.\n' "$host"
		elif [[ -z "$token" ]]; then
			# A comment, never token = "": Terraform would send an empty
			# bearer header and fail in a way that reads like a server problem.
			warn "profile '$p': no Terraform token for $host"
			printf '# No token for %s: tf_token_cmd is unset or printed nothing.\n' "$host"
			printf '# Terraform falls back to %s or a credentials helper.\n' \
				"$(sc_tf_env_name "$host")"
		elif ! sc_tf_token_ok "$token"; then
			warn "profile '$p': tf_token_cmd printed something that is not a token"
			printf '# No token for %s: tf_token_cmd printed a value that is not a token.\n' "$host"
		else
			printf 'credentials "%s" {\n  token = "%s"\n}\n' \
				"$(sc_tf_escape "$host")" "$(sc_tf_escape "$token")"
		fi
	done < <(sc_tf_hosts "$p")

	extra="$(sc_cfg_get "$p" tf_rc_extra)"
	[[ -n "$extra" ]] || return 0
	if [[ -f "$extra" ]]; then
		# Verbatim, never parsed: switchcraft has no business reading HCL, and
		# a duplicate credentials block is Terraform's own loud error.
		printf '\n# ---- appended verbatim from %s (tf_rc_extra) ----\n' "$extra"
		cat "$extra"
	else
		warn "profile '$p': tf_rc_extra does not exist: $extra"
		printf '\n# tf_rc_extra pointed at %s, which does not exist.\n' "$extra"
	fi
	return 0
}

sc_tf_rc_is_ours() {
	[[ -f "$1" ]] && grep -qF "$SC_TF_MARK" "$1" 2>/dev/null
}

# sc_tf_write_rc <profile> — returns 1 when the target is not ours to write.
sc_tf_write_rc() {
	local p="$1" f
	f="$(sc_tf_rc_file "$p")"
	if [[ -e "$f" ]] && ! sc_tf_rc_is_ours "$f"; then
		return 1
	fi
	sc_tf_rc_body "$p" | sc_write "$f" 600
}

# sc_tf_user_rc_files — the CLI configs Terraform and OpenTofu read on their
# own, and which TF_CLI_CONFIG_FILE shadows inside a managed directory.
sc_tf_user_rc_files() {
	printf '%s\n' "$HOME/.terraformrc"
	printf '%s\n' "$HOME/.tofurc"
	printf '%s\n' "$(sc_xdg_config)/opentofu/tofurc"
}

# sc_tf_rc_extra_covers <file> — true when some profile already carries that
# file into its generated config. Without this, doctor would keep nagging about
# an rc the user has already dealt with.
sc_tf_rc_extra_covers() {
	local want="$1" p extra
	want="$(sc_abs "$want")"
	while IFS= read -r p; do
		[[ -n "$p" ]] || continue
		extra="$(sc_cfg_get "$p" tf_rc_extra)"
		[[ -n "$extra" ]] || continue
		[[ "$(sc_abs "$extra")" == "$want" ]] && return 0
	done < <(sc_cfg_profiles)
	return 1
}

# sc_tf_global_creds — where `terraform login` always writes. $HOME/.terraform.d
# is relocatable by no environment variable, which is why this layer exists.
sc_tf_global_creds() { printf '%s\n' "$HOME/.terraform.d/credentials.tfrc.json"; }
