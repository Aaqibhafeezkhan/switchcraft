#!/usr/bin/env bash
# shellcheck shell=bash
# git.sh — per-profile git config, conditional includes and HTTPS credentials.

sc_git_profiles_dir() { printf '%s\n' "$(sc_xdg_config)/git-profiles"; }
sc_git_profile_file() { printf '%s\n' "$(sc_git_profiles_dir)/$1"; }
sc_git_signers_file() { printf '%s\n' "$(sc_xdg_config)/switchcraft/allowed_signers"; }

# sc_git_global_config — the file git actually reads as --global. git only falls
# back to XDG when ~/.gitconfig is absent, so honour that order instead of
# always writing ~/.gitconfig.
sc_git_global_config() {
	if [[ -f "$HOME/.gitconfig" ]]; then
		printf '%s\n' "$HOME/.gitconfig"
	elif [[ -f "$(sc_xdg_config)/git/config" ]]; then
		printf '%s\n' "$(sc_xdg_config)/git/config"
	else
		printf '%s\n' "$HOME/.gitconfig"
	fi
}

# sc_git_version_ge <major.minor>
sc_git_version_ge() {
	local want="$1" have
	has_cmd git || return 1
	have="$(git --version 2>/dev/null | awk '{print $3}')"
	[[ -n "$have" ]] || return 1
	local hm="${have%%.*}" wm="${want%%.*}"
	local hr="${have#*.}" wr="${want#*.}"
	hr="${hr%%.*}"
	wr="${wr%%.*}"
	((hm > wm)) && return 0
	((hm < wm)) && return 1
	((hr >= wr))
}

sc_git_supports_hasconfig() { sc_git_version_ge 2.36; }

# sc_git_write_profile <profile>
sc_git_write_profile() {
	local p="$1" name email key
	name="$(sc_cfg_get "$p" name)"
	email="$(sc_cfg_get "$p" email)"
	key="$(sc_profile_key "$p")"
	[[ -n "$name" && -n "$email" ]] || die "profile '$p' is missing name or email"

	sc_mkdir "$(sc_git_profiles_dir)"
	sc_render "$SC_TEMPLATES/gitconfig-profile" \
		"PROFILE=$p" "NAME=$name" "EMAIL=$email" "KEY=$key" \
		"SIGNERS=$(sc_git_signers_file)" "CREDFILE=$(sc_git_cred_file "$p")" |
		sc_write "$(sc_git_profile_file "$p")"
}

# sc_git_includes_body — the block that goes into the global gitconfig.
sc_git_includes_body() {
	local p d r path hasconfig=0
	sc_git_supports_hasconfig && hasconfig=1
	printf '# Generated by switchcraft. Edit the config, not this block:\n'
	printf '#   switchcraft link <profile> <dir>\n'
	while IFS= read -r p; do
		[[ -n "$p" ]] || continue
		path="$(sc_git_profile_file "$p")"
		while IFS= read -r d; do
			[[ -n "$d" ]] || continue
			# Canonical, because git resolves the path before matching; and the
			# trailing slash is what makes it match the whole subtree.
			printf '[includeIf "gitdir:%s/"]\n\tpath = %s\n' "$(sc_real "$d")" "$path"
		done < <(sc_cfg_get_all "$p" dir)
		while IFS= read -r r; do
			[[ -n "$r" ]] || continue
			if ((hasconfig)); then
				printf '[includeIf "hasconfig:remote.*.url:%s"]\n\tpath = %s\n' "$r" "$path"
			else
				printf '# remote match needs git >= 2.36 (have %s): %s\n' \
					"$(git --version 2>/dev/null | awk '{print $3}')" "$r"
			fi
		done < <(sc_cfg_get_all "$p" remote)
	done < <(sc_cfg_profiles)
}

sc_git_apply_includes() {
	local gc
	gc="$(sc_git_global_config)"
	sc_git_includes_body | sc_block_apply "$gc" 644
	ok "conditional includes written to $gc"
}

# ------------------------------------------------------------------
# SSH commit signing
# ------------------------------------------------------------------

# sc_git_write_signers — lets local `git log --show-signature` verify commits
# instead of reporting "No signature".
sc_git_write_signers() {
	local p email pub body=''
	while IFS= read -r p; do
		[[ -n "$p" ]] || continue
		email="$(sc_cfg_get "$p" email)"
		pub="$(sc_profile_key "$p").pub"
		[[ -f "$pub" && -n "$email" ]] || continue
		body+="$email namespaces=\"git\" $(cat "$pub")"$'\n'
	done < <(sc_cfg_profiles)
	[[ -n "$body" ]] || return 0
	printf '%s' "$body" | sc_write "$(sc_git_signers_file)" 644
}

sc_git_enable_signing() {
	sc_run git config --global gpg.format ssh
	sc_run git config --global commit.gpgsign true
	sc_run git config --global tag.gpgsign true
	sc_run git config --global gpg.ssh.allowedSignersFile "$(sc_git_signers_file)"
	ok "SSH commit signing enabled globally"
}

sc_git_disable_signing() {
	sc_run git config --global --unset-all commit.gpgsign 2>/dev/null || true
	sc_run git config --global --unset-all tag.gpgsign 2>/dev/null || true
	sc_run git config --global --unset-all gpg.ssh.allowedSignersFile 2>/dev/null || true
	sc_run git config --global --unset-all gpg.format 2>/dev/null || true
}

# ------------------------------------------------------------------
# HTTPS credentials, scoped per profile
# ------------------------------------------------------------------

sc_git_cred_file() {
	printf '%s\n' "$(sc_xdg_config)/switchcraft/credentials-$1"
}

# sc_git_cred_upsert <file> <user> <token> [host]
# Rewrites only the line for <host>, so credentials for other hosts survive.
sc_git_cred_upsert() {
	local file="$1" user="$2" token="$3" host="${4:-github.com}" kept=''
	[[ -n "$token" ]] || return 0
	if [[ -f "$file" ]]; then
		kept="$(grep -v -e "@${host}\$" -e "@${host}/" "$file" 2>/dev/null || true)"
	fi
	{
		[[ -n "$kept" ]] && printf '%s\n' "$kept"
		printf 'https://%s:%s@%s\n' "$user" "$token" "$host"
	} | sc_write "$file" 600
}
